#!/usr/bin/env python3
"""Compares ours with DOSBox on the game benchmarks, by host instructions
an emulated second over a window of each game, and prints a table per game
(markdown, also saved under hdl/target/compare).

    compare_games.py [--games lemm,jetpack,omf] [--profiles jit,blocks]
                     [--reps 3] [--no-dosbox] [--shots DIR] [--free-roms]

Before: fetch_games.sh (FreeDOS and the games), the build_*.sh scripts
(the disks), build_dosbox.sh (the patched DOSBox), and the board's ROMs in
~/roms (see fetch_games.sh).

Each window is a stretch where the game does the same thing on both, as
screenshots of both show (a menu, an attract mode), well after loading, so
neither the boot nor the disk's speed is in it. A run to the window's start
is subtracted from a run to its end.

Ours: the current tree's CLI generates the At386Vga crate for each profile
(hdl/target/compare/gen-<profile>, built in its own target directory) and
play_disk runs the disks, drawing every frame and drawing none. DOSBox: its
cycles an emulated millisecond are found so its normal core runs as many
instructions an emulated second as ours (the first profile) does in the
window; both of its cores then run at them, drawing every frame and one in
11 (`frameskip`). Each figure is the median of --reps runs.

Columns: host instructions an emulated second drawing every frame and
drawing none (DOSBox: one in 11), the drawing's share (the difference;
DOSBox's scaled to every frame), and the rest a guest instruction.
"""
import argparse, datetime, os, platform, re, resource, statistics, subprocess, sys

import perfbin

HERE = os.path.dirname(os.path.abspath(__file__))
HDL = os.path.abspath(os.path.join(HERE, "..", ".."))
DISKS = os.path.join(HDL, "target", "bench386")
WORK = os.path.join(HDL, "target", "compare")

# Windows, in emulated seconds, chosen by screenshots of both (see README).
GAMES = {
    "lemm": dict(img="lemm.img", t1=40, t2=90, keys="",
                 what="Xmas Lemmings, its main menu (a banner scrolling)"),
    "jetpack": dict(img="jetpack.img", t1=60, t2=180, keys="",
                    what="Jetpack, its attract mode (title, demo, high scores)"),
    "omf": dict(img="omf.img", hd="omf_hd.img", t1=160, t2=240, keys="45:1c",
                what="One Must Fall 2097, its main menu (music playing; Enter at 45 s)"),
}

p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
p.add_argument("--games", default="lemm,jetpack,omf")
p.add_argument("--profiles", default="jit,blocks")
p.add_argument("--reps", type=int, default=3)
p.add_argument("--no-dosbox", action="store_true")
p.add_argument("--free-roms", action="store_true",
               help="ours on the free ROMs (build_bios.sh) rather than AMI's and IBM's")
p.add_argument("--shots", help="a directory: first, an unmeasured run of each game on ours (the first "
               "profile) and DOSBox, with screenshots every 10 s to the window's end, to check the windows")
p.add_argument("--dosbox", default=os.path.join(HDL, "target", "dosbox-bench", "dosbox"))
a = p.parse_args()
PERF = perfbin.find()
# The board's ROMs: AMI's BIOS and IBM's VGA BIOS from ~/roms, or the free
# ones build_bios.sh makes there (`--free-roms`).
ROMS = {}
if a.free_roms:
    free = os.path.join(os.environ.get("PC_ROMS", os.path.expanduser("~/roms")), "free")
    ROMS = {"PC_BIOS": os.path.join(free, "BIOS-bochs-legacy-at"), "PC_VGABIOS": os.path.join(free, "VGABIOS-lgpl-latest")}
    for f in ROMS.values():
        if not os.path.exists(f):
            sys.exit(f"no {f}: run build_bios.sh")
games = a.games.split(",")
profiles = a.profiles.split(",")
for g in games:
    if g not in GAMES:
        sys.exit(f"no game {g}: {', '.join(GAMES)}")

def limit():
    # Runaway runs must not take the machine with them.
    resource.setrlimit(resource.RLIMIT_AS, (8_000_000_000, 8_000_000_000))

def run(cmd, env=None, cwd=None, timeout=3600):
    r = subprocess.run(cmd, env=env, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                       text=True, timeout=timeout, preexec_fn=limit)
    if r.returncode != 0:
        sys.exit(f"{' '.join(cmd)} failed:\n{r.stdout[-3000:]}")
    return r.stdout

def log(msg):
    print(msg, file=sys.stderr, flush=True)

# --- ours ---------------------------------------------------------------

def build(profile):
    """The At386Vga crate for a profile, generated by the tree's CLI; the
    path of its at386 test binary."""
    gen = os.path.join(WORK, f"gen-{profile}")
    pc, i386 = os.path.join(HDL, "targets", "pc"), os.path.join(HDL, "targets", "i386")
    srcs = [f"{pc}/isabus.machine", f"{pc}/crtc.machine", f"{pc}/pc.machine", f"{pc}/vga.machine",
            f"{pc}/sb.machine", f"{pc}/opl.machine", f"{HDL}/targets/i286/alu.machine",
            f"{i386}/i386.machine", f"{i386}/timing.machine", f"{i386}/board.machine"]
    run([os.path.join(HDL, "target", "release", "machine"), "build", "--system", "At386Vga",
         "--profile", profile, "--out", gen] + srcs)
    os.makedirs(os.path.join(gen, "tests"), exist_ok=True)
    with open(os.path.join(i386, "at386_test.rs")) as f, open(os.path.join(gen, "tests", "at386.rs"), "w") as o:
        o.write(f.read())
    env = dict(os.environ, CARGO_TARGET_DIR=os.path.join(WORK, f"cargo-{profile}"))
    out = run(["cargo", "test", "--release", "--manifest-path", os.path.join(gen, "Cargo.toml"),
               "--test", "at386", "--no-run", "--message-format=json"], env=env, timeout=3600)
    exe = [m for m in re.findall(r'"executable":"([^"]+)"', out)]
    if not exe:
        sys.exit(f"no test binary for {profile}")
    return exe[-1]

def perf(cmd, env):
    """Runs cmd under perf stat: (host instructions, output)."""
    stat = os.path.join(WORK, "perf.csv")
    out = run([PERF, "stat", "-x,", "-e", "instructions:u", "-o", stat] + cmd, env=env)
    host = next(int(l.split(",")[0]) for l in open(stat) if "instructions" in l)
    return host, out

def ours(exe, game, seconds, draw):
    """(host instructions, guest instructions) to `seconds`."""
    g = GAMES[game]
    env = dict(os.environ, PLAY_DISK=os.path.join(DISKS, g["img"]), PLAY_SECONDS=str(seconds),
               PLAY_EVERY="1000000", PLAY_DRAW=str(draw), PLAY_KEYS=g["keys"], **ROMS)
    if "hd" in g:
        env["PLAY_HD"] = os.path.join(DISKS, g["hd"])
    host, out = perf([exe, "--ignored", "--nocapture", "--exact", "play_disk"], env)
    m = re.search(r"PLAY .* instructions (\d+) seconds [\d.]+ .*emulated_seconds ([\d.]+)", out)
    if not m:
        sys.exit(f"play_disk gave no report:\n{out[-3000:]}")
    return host, int(m.group(1))

def ours_window(exe, game, draw):
    """Host instructions an emulated second over the window, and guest
    instructions an emulated second: medians."""
    g = GAMES[game]
    s = g["t2"] - g["t1"]
    hosts, guests = [], []
    for _ in range(a.reps):
        h1, i1 = ours(exe, game, g["t1"], draw)
        h2, i2 = ours(exe, game, g["t2"], draw)
        hosts.append((h2 - h1) / s)
        guests.append((i2 - i1) / s)
    return statistics.median(hosts), statistics.median(guests)

def ours_shots(exe, game, d):
    g = GAMES[game]
    os.makedirs(d, exist_ok=True)
    env = dict(os.environ, PLAY_DISK=os.path.join(DISKS, g["img"]), PLAY_SECONDS=str(g["t2"]),
               PLAY_EVERY="10", PLAY_SHOTS=d, PLAY_KEYS=g["keys"], **ROMS)
    if "hd" in g:
        env["PLAY_HD"] = os.path.join(DISKS, g["hd"])
    run([exe, "--ignored", "--nocapture", "--exact", "play_disk"], env=env)

# --- DOSBox -------------------------------------------------------------

def dosbox_window(game, core, cycles, frameskip):
    """Host instructions an emulated second over the window, and (normal
    core) instructions an emulated second, from one dosbox_bench.py run."""
    g = GAMES[game]
    cmd = [sys.executable, os.path.join(HERE, "dosbox_bench.py"), "--dosbox", a.dosbox, "--core", core,
           "--cycles", str(cycles), "--frameskip", str(frameskip), "--keys", g["keys"],
           os.path.join(DISKS, g["img"]), str(g["t1"]), str(g["t2"])]
    if "hd" in g:
        cmd[2:2] = ["--hd", os.path.join(DISKS, g["hd"])]
    out = run(cmd)
    m = re.search(r"window .*: ([\d.]+)G host instructions an emulated second, [\d.]+ M cycles an emulated second"
                  r"(?:, ([\d.]+) M instructions)?", out)
    if not m:
        sys.exit(f"dosbox_bench.py gave no window:\n{out[-3000:]}")
    return float(m.group(1)) * 1e9, float(m.group(2)) * 1e6 if m.group(2) else None

def dosbox_shots(game, d):
    g = GAMES[game]
    cmd = [sys.executable, os.path.join(HERE, "dosbox_bench.py"), "--dosbox", a.dosbox, "--cycles", "3000",
           "--every", "10", "--shots", d, "--keys", g["keys"], os.path.join(DISKS, g["img"]), str(g["t2"] + 1)]
    if "hd" in g:
        cmd[2:2] = ["--hd", os.path.join(DISKS, g["hd"])]
    run(cmd, env=dict(os.environ, PERF="none"))

def dosbox_median(game, core, cycles, frameskip):
    return statistics.median(dosbox_window(game, core, cycles, frameskip)[0] for _ in range(a.reps))

def match_cycles(game, rate):
    """DOSBox's cycles an emulated millisecond at which its normal core runs
    `rate` instructions an emulated second in the window (within 2%)."""
    cycles, got = 3000, None
    tried = []
    for _ in range(6):
        got = dosbox_window(game, "normal", cycles, 10)[1]
        tried.append((cycles, got))
        log(f"  {game}: DOSBox at {cycles} cycles/ms runs {got / 1e6:.2f} M instructions/s (ours {rate / 1e6:.2f} M)")
        if abs(got - rate) <= 0.02 * rate:
            break
        if len(tried) >= 2 and tried[-1][1] != tried[-2][1]:
            (c0, r0), (c1, r1) = tried[-2], tried[-1]
            nxt = c1 + (rate - r1) * (c1 - c0) / (r1 - r0)
        else:
            nxt = cycles * rate / got
        cycles = max(100, int(round(nxt / 10)) * 10)
    return cycles, got

# --- the table -----------------------------------------------------------

def commit():
    rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HDL, capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=HDL,
                           capture_output=True, text=True).stdout.strip()
    return rev + (" (with changes)" if dirty else "")

def cpu():
    try:
        for l in open("/proc/cpuinfo"):
            if l.startswith("model name"):
                return l.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"

def g_(x):
    return f"{x / 1e9:.2f} G"

os.makedirs(WORK, exist_ok=True)
log("building the CLI")
run(["cargo", "build", "--release", "--bin", "machine"], cwd=HDL)
exes = {}
for pr in profiles:
    log(f"generating and building {pr}")
    exes[pr] = build(pr)
if not a.no_dosbox and not os.path.exists(a.dosbox):
    sys.exit(f"no {a.dosbox}: run build_dosbox.sh (or pass --no-dosbox)")

if a.shots:
    for game in games:
        log(f"{game}: screenshots into {a.shots}")
        ours_shots(exes[profiles[0]], game, os.path.join(a.shots, f"{game}-ours"))
        if not a.no_dosbox:
            dosbox_shots(game, os.path.join(a.shots, f"{game}-dosbox"))

when = datetime.date.today().isoformat()
lines = [f"Games compared {when}, commit {commit()}, on {cpu()}" + (", ours on the free ROMs" if a.free_roms else "")
         + f"; host instructions an emulated second, medians of {a.reps}.", ""]
for game in games:
    g = GAMES[game]
    rows = []
    rate = None
    for pr in profiles:
        log(f"{game}: ours, {pr}")
        full, guest = ours_window(exes[pr], game, 1)
        none, _ = ours_window(exes[pr], game, 0)
        rate = rate or guest
        rows.append((f"ours, `{pr}`", full, f"{g_(none)} (none)", full - none, none / guest, guest))
    head = f"{g['what']}, {g['t1']} s to {g['t2']} s"
    if not a.no_dosbox:
        cycles, drate = match_cycles(game, rate)
        head += f"; DOSBox at `cycles=fixed {cycles}`"
        for core in ["normal", "dynamic"]:
            log(f"{game}: DOSBox, {core}")
            full = dosbox_median(game, core, cycles, 0)
            fs = dosbox_median(game, core, cycles, 10)
            draw = (full - fs) * 11 / 10
            rows.append((f"DOSBox 0.74-3, {core}", full, f"{g_(fs)} (1 in 11)", draw, (fs - draw / 11) / drate, drate))
    lines += [head + ":", "",
              "| | every frame | drawing none | drawing | the rest, a guest instruction | guest instructions an emulated second |",
              "|---|---|---|---|---|---|"]
    for name, full, none, draw, per, guest in rows:
        lines.append(f"| {name} | {g_(full)} | {none} | {g_(draw)} | {per:.0f} | {guest / 1e6:.2f} M |")
    lines.append("")

text = "\n".join(lines)
print(text)
path = os.path.join(WORK, f"compare-{when}-{commit().split()[0]}.md")
with open(path, "w") as f:
    f.write(text)
log(f"saved {path}")
